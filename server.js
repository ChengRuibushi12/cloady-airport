// ---- Fork change: real traffic counting ----
// Cloady free tier: 10 GiB outbound per calendar month (UTC reset).
// Count bytes in the WebSocket forwarding layer:
//   client -> Xray  = upload, Xray -> client = download.
// Stored in traffic.json next to server.js (falls back to /tmp),
// reset automatically when the UTC month changes.
// NOTE: the counter lives in the container filesystem, so a
// redeploy / rebuild resets it to zero. UUID and WS path unchanged.
const TRAFFIC_TOTAL = 10 * 1024 * 1024 * 1024; // 10737418240
const TRAFFIC_FILE = path.join(__dirname, 'traffic.json');
const TRAFFIC_FILE_FALLBACK = '/tmp/traffic.json';

function currentMonthUTC() {
  const d = new Date();
  return d.getUTCFullYear() + '-' + String(d.getUTCMonth() + 1).padStart(2, '0');
}

let traffic = { month: currentMonthUTC(), upload: 0, download: 0 };
let trafficFile = TRAFFIC_FILE;
let trafficDirty = false;

function loadTraffic() {
  for (const f of [TRAFFIC_FILE, TRAFFIC_FILE_FALLBACK]) {
    try {
      const data = JSON.parse(fs.readFileSync(f, 'utf8'));
      if (data && typeof data.upload === 'number' && typeof data.download === 'number') {
        trafficFile = f;
        if (data.month === currentMonthUTC()) {
          traffic = { month: data.month, upload: data.upload, download: data.download };
        } else {
          traffic = { month: currentMonthUTC(), upload: 0, download: 0 };
          saveTraffic();
        }
        return;
      }
    } catch (e) { /* file missing or unreadable: start from zero */ }
  }
}

function saveTraffic() {
  try {
    fs.writeFileSync(trafficFile, JSON.stringify(traffic));
  } catch (e) {
    try {
      trafficFile = TRAFFIC_FILE_FALLBACK;
      fs.writeFileSync(trafficFile, JSON.stringify(traffic));
    } catch (e2) { /* counting continues in memory only */ }
  }
}

function checkMonthReset() {
  const m = currentMonthUTC();
  if (traffic.month !== m) {
    traffic = { month: m, upload: 0, download: 0 };
    saveTraffic();
  }
}

function addUpload(n) { checkMonthReset(); traffic.upload += n; trafficDirty = true; }
function addDownload(n) { checkMonthReset(); traffic.download += n; trafficDirty = true; }

loadTraffic();
setInterval(() => { if (trafficDirty) { saveTraffic(); trafficDirty = false; } }, 15000).unref();

function formatBytes(n) {
  if (n < 1024) return n + ' B';
  if (n < 1024 * 1024) return (n / 1024).toFixed(1) + ' KB';
  if (n < 1024 * 1024 * 1024) return (n / (1024 * 1024)).toFixed(2) + ' MB';
  return (n / (1024 * 1024 * 1024)).toFixed(2) + ' GB';
}

function usageHeader() {
  checkMonthReset();
  return 'upload=' + traffic.upload + '; download=' + traffic.download + '; total=' + TRAFFIC_TOTAL + '; expire=0';
}

function metered(addBytes) {
  return new Transform({
    transform(chunk, _enc, cb) { addBytes(chunk.length); cb(null, chunk); }
  });
}

