// 4. WebSocket 流量反向代理到 127.0.0.1:10000 (Xray)
server.on('upgrade', (req, clientSocket, head) => {
  const reqUrl = req.url || '';
  const matchPath = '/' + WS_PATH;

  if (reqUrl === matchPath || reqUrl.startsWith(matchPath + '?') || reqUrl.startsWith(matchPath + '/')) {
    const proxySocket = net.connect(XRAY_PORT, '127.0.0.1', () => {
      proxySocket.write(`${req.method} ${req.url} HTTP/${req.httpVersion}\r\n`);
      for (let i = 0; i < req.rawHeaders.length; i += 2) {
        proxySocket.write(`${req.rawHeaders[i]}: ${req.rawHeaders[i + 1]}\r\n`);
      }
      proxySocket.write('\r\n');
      if (head && head.length) {
        proxySocket.write(head);
      }
      clientSocket.pipe(proxySocket);
      proxySocket.pipe(clientSocket);
    });

    proxySocket.on('error', (err) => {
      clientSocket.destroy();
    });

    clientSocket.on('error', (err) => {
      proxySocket.destroy();
    });
  } else {
    clientSocket.destroy();
  }
});

