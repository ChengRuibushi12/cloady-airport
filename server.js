// 4. WebSocket 流量反向代理到 127.0.0.1:10000 (Xray)，转发层计量流量
server.on('upgrade', (req, clientSocket, head) => {
  const reqUrl = req.url || '';
  const matchPath = '/' + WS_PATH;

  if (reqUrl === matchPath || reqUrl.startsWith(matchPath + '?') || reqUrl.startsWith(matchPath + '/')) {
    const proxySocket = net.connect(XRAY_PORT, '127.0.0.1', () => {
      let headerBlock = `${req.method} ${req.url} HTTP/${req.httpVersion}\r\n`;
      for (let i = 0; i < req.rawHeaders.length; i += 2) {
        headerBlock += `${req.rawHeaders[i]}: ${req.rawHeaders[i + 1]}\r\n`;
      }
      headerBlock += '\r\n';
      // 注意：不要再对 headerBlock 单独计数——实测发现 Node 在 upgrade 后
      // 把请求头字节也会经 pipe 重新送出（经 metered 已计一次），单独再计会翻倍。
      // head 是解析器已读出的正文外数据，不会经 pipe 重放，才需要单独计。
      proxySocket.write(headerBlock);

      if (head && head.length) {
        addUpload(head.length);
        proxySocket.write(head);
      }

      // 客户端 -> Xray 计为上传，Xray -> 客户端计为下载
      clientSocket.pipe(metered(addUpload)).pipe(proxySocket);
      proxySocket.pipe(metered(addDownload)).pipe(clientSocket);
    });

    const saveOnEnd = () => { if (trafficDirty) { saveTraffic(); trafficDirty = false; } };
    proxySocket.on('close', saveOnEnd);
    clientSocket.on('close', saveOnEnd);

    proxySocket.on('error', (err) => {
      saveOnEnd();
      clientSocket.destroy();
    });

    clientSocket.on('error', (err) => {
      saveOnEnd();
      proxySocket.destroy();
    });
  } else {
    clientSocket.destroy();
  }
});

